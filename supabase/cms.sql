-- Blog posts. Existing installations are upgraded in place.
create table if not exists public.posts (
  id text primary key,
  slug text not null unique,
  title text not null,
  date text not null,
  read_time text,
  excerpt text not null default '',
  content text not null default '',
  status text not null default 'published',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

alter table public.posts add column if not exists status text not null default 'published';
alter table public.posts add column if not exists published_at timestamptz;
update public.posts set status = 'published' where status is null;

alter table public.posts enable row level security;
-- Remove legacy read policies from the previous instant-blog setup. Keeping an
-- old `using (true)` policy would accidentally expose newly-created drafts.
do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = 'posts'
      and cmd in ('SELECT', 'ALL')
  loop
    execute format('drop policy if exists %I on public.posts', existing_policy.policyname);
  end loop;
end;
$$;

create policy "Public can read published posts"
on public.posts for select
to anon, authenticated
using (status = 'published');
grant select on public.posts to anon, authenticated;

-- Durable contact inbox. There is intentionally no public policy; only the
-- service-role API can insert or read messages.
create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  message text not null check (char_length(message) between 1 and 5000),
  status text not null default 'new' check (status in ('new', 'read', 'archived')),
  created_at timestamptz not null default now()
);

create index if not exists contact_messages_status_created_idx
  on public.contact_messages (status, created_at desc);

alter table public.contact_messages enable row level security;
revoke all on public.contact_messages from anon, authenticated;

