create extension if not exists pgcrypto;

-- Private working documents. The browser never queries this table directly;
-- authenticated admin route handlers use the server-side service role.
create table if not exists public.cms_entries (
  key text primary key check (key ~ '^[a-zA-Z][a-zA-Z0-9_-]{1,79}$'),
  label text not null,
  section text not null default 'custom',
  description text not null default '',
  content_type text not null default 'object',
  draft_content jsonb not null default '{}'::jsonb,
  published_content jsonb,
  version integer not null default 1 check (version > 0),
  sort_order integer not null default 999,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

create table if not exists public.cms_revisions (
  id bigint generated by default as identity primary key,
  entry_key text not null references public.cms_entries(key) on delete cascade,
  version integer not null,
  content jsonb not null,
  change_type text not null default 'draft' check (change_type in ('draft', 'publish', 'restore')),
  created_at timestamptz not null default now()
);

create index if not exists cms_revisions_entry_created_idx
  on public.cms_revisions (entry_key, created_at desc);

-- Only this projection is exposed to visitors. It contains no draft column.
create table if not exists public.cms_published (
  key text primary key,
  content jsonb not null,
  version integer not null,
  published_at timestamptz not null default now()
);

create or replace function public.cms_prepare_entry_update()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.updated_at = now();
  if new.draft_content is distinct from old.draft_content then
    new.version = old.version + 1;
  end if;
  return new;
end;
$$;

drop trigger if exists cms_prepare_entry_update_trigger on public.cms_entries;
create trigger cms_prepare_entry_update_trigger
before update on public.cms_entries
for each row execute function public.cms_prepare_entry_update();

create or replace function public.cms_record_draft_revision()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' or new.draft_content is distinct from old.draft_content then
    insert into public.cms_revisions (entry_key, version, content, change_type)
    values (new.key, new.version, new.draft_content, 'draft');
  end if;
  return new;
end;
$$;

drop trigger if exists cms_record_draft_revision_trigger on public.cms_entries;
create trigger cms_record_draft_revision_trigger
after insert or update on public.cms_entries
for each row execute function public.cms_record_draft_revision();

-- Atomically copies a private draft into the public read model.
create or replace function public.cms_publish_entry(p_key text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_entry public.cms_entries%rowtype;
begin
  select * into current_entry
  from public.cms_entries
  where key = p_key
  for update;

  if not found then
    raise exception 'CMS entry % does not exist', p_key;
  end if;

  update public.cms_entries
  set published_content = current_entry.draft_content,
      published_at = now()
  where key = p_key;

  insert into public.cms_published (key, content, version, published_at)
  values (p_key, current_entry.draft_content, current_entry.version, now())
  on conflict (key) do update
    set content = excluded.content,
        version = excluded.version,
        published_at = excluded.published_at;

  insert into public.cms_revisions (entry_key, version, content, change_type)
  values (p_key, current_entry.version, current_entry.draft_content, 'publish');
end;
$$;

create or replace function public.cms_restore_revision(p_key text, p_revision_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  restored_content jsonb;
begin
  select content into restored_content
  from public.cms_revisions
  where id = p_revision_id and entry_key = p_key;

  if restored_content is null then
    raise exception 'Revision % for CMS entry % does not exist', p_revision_id, p_key;
  end if;

  update public.cms_entries
  set draft_content = restored_content
  where key = p_key;

  if not found then
    raise exception 'CMS entry % does not exist', p_key;
  end if;
end;
$$;

revoke all on function public.cms_publish_entry(text) from public, anon, authenticated;
revoke all on function public.cms_restore_revision(text, bigint) from public, anon, authenticated;
grant execute on function public.cms_publish_entry(text) to service_role;
grant execute on function public.cms_restore_revision(text, bigint) to service_role;

alter table public.cms_entries enable row level security;
alter table public.cms_revisions enable row level security;
alter table public.cms_published enable row level security;

